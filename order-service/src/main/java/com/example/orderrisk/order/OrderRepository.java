import com.example.orderrisk.common.Telemetry;
import com.example.orderrisk.order.OrderModels.CustomerOrderSummary;
import com.example.orderrisk.order.OrderModels.InvalidTransitionException;
import com.example.orderrisk.order.OrderModels.ItemPrice;
import com.example.orderrisk.order.OrderModels.NewOrder;
import com.example.orderrisk.order.OrderModels.NewOrderItem;
import com.example.orderrisk.order.OrderModels.Order;
import com.example.orderrisk.order.OrderModels.OrderItem;
import com.example.orderrisk.order.OrderModels.OrderNotFoundException;
import com.example.orderrisk.order.OrderModels.OrderStatus;
import com.example.orderrisk.order.OrderModels.OrderSummary;
import com.example.orderrisk.order.OrderModels.RiskResult;
import com.example.orderrisk.order.OrderModels.RiskResultUpdate;
import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.StatusCode;
import io.opentelemetry.context.Scope;

import javax.sql.DataSource;
import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Timestamp;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;
import java.util.stream.Collectors;

/**
 * Plain JDBC access to the order-service H2 database.
 * Every public method borrows one connection from the HikariCP pool and is traced as one span.
 */
public class OrderRepository {

    private final DataSource dataSource;

    public OrderRepository(DataSource dataSource) {
        this.dataSource = dataSource;
    }

    public void createSchema() {
        inTransaction("CREATE TABLE", connection -> {
            try (Statement st = connection.createStatement()) {
                st.execute("""
                        CREATE TABLE IF NOT EXISTS orders (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            customer_id VARCHAR(20) NOT NULL,
                            shipping_address VARCHAR(200) NOT NULL,
                            shipping_country CHAR(2) NOT NULL,
                            status VARCHAR(16) NOT NULL,
                            status_reason VARCHAR(500),
                            total_amount DECIMAL(12, 2),
                            created_at TIMESTAMP NOT NULL,
                            updated_at TIMESTAMP NOT NULL)""");
                st.execute("""
                        CREATE TABLE IF NOT EXISTS order_items (
                            order_id BIGINT NOT NULL REFERENCES orders(id),
                            line_no INT NOT NULL,
                            sku VARCHAR(32) NOT NULL,
                            quantity INT NOT NULL,
                            unit_price DECIMAL(12, 2),
                            PRIMARY KEY (order_id, line_no))""");
                st.execute("""
                        CREATE TABLE IF NOT EXISTS risk_results (
                            order_id BIGINT PRIMARY KEY REFERENCES orders(id),
                            score DOUBLE PRECISION NOT NULL,
                            category VARCHAR(8) NOT NULL,
                            work_factor INT NOT NULL,
                            evaluated_at TIMESTAMP NOT NULL)""");
                st.execute("CREATE INDEX IF NOT EXISTS idx_orders_customer ON orders(customer_id)");
            }
            return null;
        });
    }

    /** Stores a new order in state SUBMITTED. */
    public Order create(NewOrder order) {
        long id = inTransaction("INSERT orders", connection -> {
            Timestamp now = Timestamp.from(Instant.now());
            long orderId;
            try (PreparedStatement ps = connection.prepareStatement(
                    "INSERT INTO orders (customer_id, shipping_address, shipping_country, status, created_at, updated_at) "
                            + "VALUES (?, ?, ?, ?, ?, ?)", Statement.RETURN_GENERATED_KEYS)) {
                ps.setString(1, order.customerId());
                ps.setString(2, order.shippingAddress());
                ps.setString(3, order.shippingCountry());
                ps.setString(4, OrderStatus.SUBMITTED.name());
                ps.setTimestamp(5, now);
                ps.setTimestamp(6, now);
                ps.executeUpdate();
                try (ResultSet keys = ps.getGeneratedKeys()) {
                    keys.next();
                    orderId = keys.getLong(1);
                }
            }
            try (PreparedStatement ps = connection.prepareStatement(
                    "INSERT INTO order_items (order_id, line_no, sku, quantity) VALUES (?, ?, ?, ?)")) {
                int line = 1;
                for (NewOrderItem item : order.items()) {
                    ps.setLong(1, orderId);
                    ps.setInt(2, line++);
                    ps.setString(3, item.sku());
                    ps.setInt(4, item.quantity());
                    ps.addBatch();
                }
                ps.executeBatch();
            }
            return orderId;
        });
        return find(id);
    }

    public Order find(long id) {
        return inTransaction("SELECT orders", connection -> {
            Order order = loadOrder(connection, id);
            if (order == null) {
                throw new OrderNotFoundException(id);
            }
            return order;
        });
    }

    public List<OrderSummary> listRecent(int limit) {
        return inTransaction("SELECT orders", connection -> {
            List<OrderSummary> result = new ArrayList<>();
            try (PreparedStatement ps = connection.prepareStatement(
                    "SELECT o.id, o.customer_id, o.status, o.total_amount, r.category, o.created_at "
                            + "FROM orders o LEFT JOIN risk_results r ON r.order_id = o.id "
                            + "ORDER BY o.id DESC LIMIT ?")) {
                ps.setInt(1, limit);
                try (ResultSet rs = ps.executeQuery()) {
                    while (rs.next()) {
                        result.add(new OrderSummary(rs.getLong(1), rs.getString(2), OrderStatus.valueOf(rs.getString(3)),
                                rs.getBigDecimal(4), rs.getString(5), rs.getTimestamp(6).toInstant().toString()));
                    }
                }
            }
            return result;
        });
    }

    /**
     * Changes the order status, but only if the transition is allowed by the state machine
     * ({@link OrderModels#allowedPredecessors}). The check and the update are one SQL statement,
     * so concurrent updates from different services cannot move an order backwards.
     */
    public Order updateStatus(long id, OrderStatus target, String reason) {
        inTransaction("UPDATE orders", connection -> {
            Set<OrderStatus> from = OrderModels.allowedPredecessors(target);
            int updated = 0;
            if (!from.isEmpty()) {
                String placeholders = from.stream().map(s -> "?").collect(Collectors.joining(", "));
                try (PreparedStatement ps = connection.prepareStatement(
                        "UPDATE orders SET status = ?, status_reason = ?, updated_at = ? WHERE id = ? AND status IN ("
                                + placeholders + ")")) {
                    ps.setString(1, target.name());
                    ps.setString(2, reason);
                    ps.setTimestamp(3, Timestamp.from(Instant.now()));
                    ps.setLong(4, id);
                    int index = 5;
                    for (OrderStatus status : from) {
                        ps.setString(index++, status.name());
                    }
                    updated = ps.executeUpdate();
                }
            }
            if (updated == 0) {
                throw transitionFailure(connection, id, target);
            }
            return null;
        });
        return find(id);
    }

    /** Stores the risk result and price snapshot, and moves the order from PROCESSING to COMPLETED. */
    public Order saveRiskResult(long id, RiskResultUpdate result) {
        inTransaction("INSERT risk_results", connection -> {
            Timestamp now = Timestamp.from(Instant.now());
            try (PreparedStatement ps = connection.prepareStatement(
                    "UPDATE orders SET status = ?, status_reason = NULL, total_amount = ?, updated_at = ? "
                            + "WHERE id = ? AND status = ?")) {
                ps.setString(1, OrderStatus.COMPLETED.name());
                ps.setBigDecimal(2, result.totalAmount());
                ps.setTimestamp(3, now);
                ps.setLong(4, id);
                ps.setString(5, OrderStatus.PROCESSING.name());
                if (ps.executeUpdate() == 0) {
                    throw transitionFailure(connection, id, OrderStatus.COMPLETED);
                }
            }
            try (PreparedStatement ps = connection.prepareStatement(
                    "UPDATE order_items SET unit_price = ? WHERE order_id = ? AND sku = ?")) {
                for (ItemPrice price : result.itemPrices()) {
                    ps.setBigDecimal(1, price.unitPrice());
                    ps.setLong(2, id);
                    ps.setString(3, price.sku());
                    ps.addBatch();
                }
                ps.executeBatch();
            }
            try (PreparedStatement ps = connection.prepareStatement(
                    "INSERT INTO risk_results (order_id, score, category, work_factor, evaluated_at) VALUES (?, ?, ?, ?, ?)")) {
                ps.setLong(1, id);
                ps.setDouble(2, result.score());
                ps.setString(3, result.category());
                ps.setInt(4, result.workFactor());
                ps.setTimestamp(5, now);
                ps.executeUpdate();
            }
            return null;
        });
        return find(id);
    }

    public CustomerOrderSummary customerSummary(String customerId) {
        return inTransaction("SELECT orders", connection -> {
            try (PreparedStatement ps = connection.prepareStatement(
                    "SELECT COUNT(*), "
                            + "SUM(CASE WHEN o.status = 'COMPLETED' THEN 1 ELSE 0 END), "
                            + "SUM(CASE WHEN r.category = 'HIGH' THEN 1 ELSE 0 END), "
                            + "SUM(CASE WHEN o.status = 'COMPLETED' THEN o.total_amount ELSE 0 END) "
                            + "FROM orders o LEFT JOIN risk_results r ON r.order_id = o.id WHERE o.customer_id = ?")) {
                ps.setString(1, customerId);
                try (ResultSet rs = ps.executeQuery()) {
                    rs.next();
                    BigDecimal amount = rs.getBigDecimal(4);
                    return new CustomerOrderSummary(customerId, rs.getInt(1), rs.getInt(2), rs.getInt(3),
                            amount == null ? BigDecimal.ZERO.setScale(2) : amount);
                }
            }
        });
    }

    private Order loadOrder(Connection connection, long id) throws SQLException {
        try (PreparedStatement ps = connection.prepareStatement(
                "SELECT id, customer_id, shipping_address, shipping_country, status, status_reason, total_amount, "
                        + "created_at, updated_at FROM orders WHERE id = ?")) {
            ps.setLong(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                if (!rs.next()) {
                    return null;
                }
                return new Order(rs.getLong(1), rs.getString(2), rs.getString(3), rs.getString(4),
                        OrderStatus.valueOf(rs.getString(5)), rs.getString(6), rs.getBigDecimal(7),
                        rs.getTimestamp(8).toInstant().toString(), rs.getTimestamp(9).toInstant().toString(),
                        loadItems(connection, id), loadRiskResult(connection, id));
            }
        }
    }

    private List<OrderItem> loadItems(Connection connection, long id) throws SQLException {
        List<OrderItem> items = new ArrayList<>();
        try (PreparedStatement ps = connection.prepareStatement(
                "SELECT line_no, sku, quantity, unit_price FROM order_items WHERE order_id = ? ORDER BY line_no")) {
            ps.setLong(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    items.add(new OrderItem(rs.getInt(1), rs.getString(2), rs.getInt(3), rs.getBigDecimal(4)));
                }
            }
        }
        return items;
    }

    private RiskResult loadRiskResult(Connection connection, long id) throws SQLException {
        try (PreparedStatement ps = connection.prepareStatement(
                "SELECT score, category, work_factor, evaluated_at FROM risk_results WHERE order_id = ?")) {
            ps.setLong(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next()
                        ? new RiskResult(rs.getDouble(1), rs.getString(2), rs.getInt(3), rs.getTimestamp(4).toInstant().toString())
                        : null;
            }
        }
    }

    private RuntimeException transitionFailure(Connection connection, long id, OrderStatus target) throws SQLException {
        try (PreparedStatement ps = connection.prepareStatement("SELECT status FROM orders WHERE id = ?")) {
            ps.setLong(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                if (!rs.next()) {
                    return new OrderNotFoundException(id);
                }
                return new InvalidTransitionException(id, OrderStatus.valueOf(rs.getString(1)), target);
            }
        }
    }

    @FunctionalInterface
    interface SqlWork<T> {
        T execute(Connection connection) throws SQLException;
    }

    /**
     * Runs {@code work} in one database transaction inside a CLIENT span named after the SQL
     * operation. The span includes the time spent waiting for a pooled connection.
     */
    private <T> T inTransaction(String operation, SqlWork<T> work) {
        Span span = Telemetry.tracer().spanBuilder(operation)
                .setSpanKind(SpanKind.CLIENT)
                .setAttribute("db.system", "h2")
                .setAttribute("db.operation.name", operation.substring(0, operation.indexOf(' ')))
                .startSpan();
        try (Scope ignored = span.makeCurrent(); Connection connection = dataSource.getConnection()) {
            connection.setAutoCommit(false);
            try {
                T result = work.execute(connection);
                connection.commit();
                return result;
            } catch (SQLException | RuntimeException e) {
                connection.rollback();
                throw e;
            }
        } catch (SQLException e) {
            span.recordException(e);
            span.setStatus(StatusCode.ERROR);
            throw new DatabaseException(e);
        } finally {
            span.end();
        }
    }

    public static class DatabaseException extends RuntimeException {
        public DatabaseException(SQLException cause) {
            super("database unavailable: " + cause.getMessage(), cause);
        }
    }
}
